/** Builds an amount DTO. `amount` is an exact decimal string; never pass a float. */
export function vnd(amount: string, sign: "" | "+" | "−" = "") {
  const negative = amount.startsWith("-");
  const digits = negative ? amount.slice(1) : amount;
  const formatted = new Intl.NumberFormat("vi-VN").format(BigInt(digits));
  const prefix = sign || (negative ? "−" : "");
  return { value: { amount, currency: "VND" }, display: `${prefix}${formatted} ₫` };
}

function posted(
  id: string,
  occurredAt: string,
  kind: DemoTransaction["kind"],
  title: string,
  category: string | null,
  amount: string,
  sourceAccountId: string,
  destinationAccountId: string | null = null,
): DemoTransaction {
  return {
    id,
    workspaceId,
    occurredAt,
    kind,
    status: "posted",
    title,
    category,
    amount: vnd(amount, kind === "expense" ? "−" : kind === "income" ? "+" : ""),
    pnlImpact: kind !== "transfer",
    sourceAccountId,
    destinationAccountId,
    note: "",
    source: "mock-json",
  };
}

